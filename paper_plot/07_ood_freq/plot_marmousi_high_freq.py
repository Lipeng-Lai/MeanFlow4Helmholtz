"""Generate 17/18 Hz Marmousi comparison figures using the 05 configuration.

Run without arguments to generate both frequencies. Use ``--frequency 17``
or ``--frequency 18`` for a single frequency and ``--component imag`` for
the imaginary wavefield. Missing fields are generated by the shared loader
using the repository Helmholtz solver and its residual tolerance.
"""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path


HERE = Path(__file__).resolve().parent
COMPARISON_SCRIPT = HERE.parent / "05_Marmousi" / "plot_marmousi.py"


def configure_plot(frequency_hz: int):
    spec = importlib.util.spec_from_file_location(
        f"marmousi_{frequency_hz}hz_comparison", COMPARISON_SCRIPT
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load Marmousi comparison: {COMPARISON_SCRIPT}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    plot = module.PLOT

    # Keep the model, source, prediction steps and style from 05_Marmousi.
    # Append both OOD frequencies so the index convention is the same for
    # either invocation; stored test fields are identified by frequency.
    plot.FREQUENCIES_HZ = sorted(set(plot.FREQUENCIES_HZ) | {17, 18})
    plot.FREQUENCY_INDEX = plot.FREQUENCIES_HZ.index(frequency_hz)
    plot.SAMPLE_INDEX = (
        plot.MODEL_INDEX * len(plot.FREQUENCIES_HZ) * plot.SOURCE_COUNT
        + plot.FREQUENCY_INDEX * plot.SOURCE_COUNT
        + plot.SOURCE_INDEX
    )
    plot.OUTPUT_DIR = HERE
    plot.OUTPUT_STEM = f"marmousi_{frequency_hz}hz_comparison"
    # Use ±0.2 for wavefields and the tighter ±0.05 scale for residuals.
    plot.BACKGROUND_VMIN, plot.BACKGROUND_VMAX = -2.0e-1, 2.0e-1
    plot.PREDICTION_VMIN, plot.PREDICTION_VMAX = -2.0e-1, 2.0e-1
    plot.ERROR_VMIN, plot.ERROR_VMAX = -5.0e-2, 5.0e-2
    if frequency_hz == 18:
        # Move the sampling legend down so it does not cover the high-step
        # curves in the 18 Hz panel (the 17 Hz panel keeps its default place).
        plot.SAMPLING_LEGEND_LOC = "upper right"
        plot.SAMPLING_LEGEND_BBOX_TO_ANCHOR = (0.98, 0.78)
    return plot


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--frequency", type=int, choices=(17, 18), nargs="+", default=[17, 18],
        help="frequency or frequencies to plot in Hz (default: 17 18)",
    )
    parser.add_argument("--component", choices=("real", "imag"), default="real")
    args = parser.parse_args()
    for frequency in dict.fromkeys(args.frequency):
        plot = configure_plot(frequency)
        print(
            f"Marmousi {frequency} Hz: model={plot.MODEL_INDEX}, "
            f"source=(x, z)=({plot.SOURCE_X_INDICES[plot.SOURCE_INDEX]}, "
            f"{plot.SOURCE_Z_INDEX}), prediction_steps={plot.PREDICTION_STEPS}, "
            f"sampling_steps={plot.SAMPLING_STEPS}",
            flush=True,
        )
        plot.main(argparse.Namespace(component=args.component))


if __name__ == "__main__":
    main()
